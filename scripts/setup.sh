#!/bin/sh
# =============================================================================
# setup.sh — 新しいマシンのセットアップをまとめて実行する
#
# やること:
#   1. 設定ファイルへのリンクを作る          (link.sh)
#   2. Homebrew とパッケージを入れる          (install.sh)
#   3. 普段使うシェルを zsh に変える
#   4. Neovim のプラグインを入れる
#
#   使い方: ./scripts/setup.sh
# =============================================================================
set -eu

dotfiles_root=$(cd "$(dirname "$0")/.." && pwd)
. "${dotfiles_root}/scripts/common.sh"


# -----------------------------------------------------------------------------
# 1. リンクを作る / 2. パッケージを入れる
# -----------------------------------------------------------------------------
"${dotfiles_root}/scripts/link.sh"
"${dotfiles_root}/scripts/install.sh"

# install.sh は別のプロセスとして動くので、その中で通した PATH は
# こちらには残らない。brew を使えるように改めて設定する
# (失敗しても続けたいので || true を付けている)
__load_brew || true


# -----------------------------------------------------------------------------
# 3. 普段使うシェルを zsh に変える
# -----------------------------------------------------------------------------
zsh_path=$(command -v zsh || true)

if [ -n "$zsh_path" ] && [ "$(basename "${SHELL:-}")" != "zsh" ]; then

    # /etc/shells は「ログインシェルとして許可されたコマンド」の一覧。
    # ここに載っていないと chsh が拒否されるので、無ければ追記する
    if ! grep -qx "$zsh_path" /etc/shells 2>/dev/null; then
        echo "$zsh_path" | sudo tee -a /etc/shells >/dev/null
    fi

    # chsh はログインシェルを変更するコマンド
    if chsh -s "$zsh_path"; then
        __info "ログインシェルを変更: $zsh_path"
    else
        __warn "chshに失敗しました。手動で変更してください: chsh -s $zsh_path"
    fi
fi


# -----------------------------------------------------------------------------
# 4. Neovim のプラグインを入れる
#
# lazy-lock.json に「どのプラグインをどのバージョンで使うか」が
# 記録してあるので、その通りに復元する
# -----------------------------------------------------------------------------
if command -v nvim >/dev/null 2>&1; then
    __info "Neovimプラグインを復元中..."

    # --headless は画面を出さずに実行する指定
    nvim --headless "+Lazy! restore" +qa \
        || __warn "Neovimプラグインの復元に失敗しました。nvim起動後に :Lazy restore を実行してください"
fi


__info "セットアップ完了。ターミナルを開き直してください"
